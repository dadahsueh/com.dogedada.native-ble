#!/usr/bin/env python3
"""
Cross-platform C# binding generator for Unity Native BLE.
Regenerates the C# bindings from the Rust FFI definitions with safe Unity types.
"""

import os
import re
import subprocess
import sys
from pathlib import Path

def post_process_bindings(content: str) -> str:
    """
    Post-process the generated C# bindings to improve naming and safety for Unity.
    """
    content = content.replace("namespace My.Company", "namespace UnityNativeBLE")
    content = content.replace("\nusing My.Company;", "")
    content = content.replace("public static partial class Interop", "public static partial class NativeBLE")
    content = content.replace("static Interop()", "static NativeBLE()")

    content = content.replace(
        'public const string NativeLib = "libunity_native_ble";',
        'public const string NativeLib = "unity_native_ble";'
    )

    content = content.replace(
        "// Automatically generated by Interoptopus.",
        "// Automatically generated by Interoptopus and post-processed for Unity.\n// Unity Native BLE Plugin - Native C# Bindings"
    )

    # Replace C-string pointer `ref sbyte <param>` with safe `[MarshalAs(UnmanagedType.LPStr)] string <param>`
    content = re.sub(
        r'ref sbyte (\w+)',
        r'[MarshalAs(UnmanagedType.LPStr)] string \1',
        content
    )

    # Replace output buffer pointers `out byte <buffer>` with safe `[Out] byte[] <buffer>`
    content = re.sub(
        r'out byte (out_buffer|data)',
        r'[Out] byte[] \1',
        content
    )

    # Replace input buffer pointer `ref byte data` with safe `[In] byte[] data`
    content = re.sub(
        r'ref byte data',
        r'[In] byte[] data',
        content
    )

    # Inject convenience methods into BLEUuid struct
    uuid_helpers = """
        public static BLEUuid FromGuid(Guid guid)
        {
            byte[] bytes = guid.ToByteArray();
            return new BLEUuid
            {
                data0 = bytes[0], data1 = bytes[1], data2 = bytes[2], data3 = bytes[3],
                data4 = bytes[4], data5 = bytes[5], data6 = bytes[6], data7 = bytes[7],
                data8 = bytes[8], data9 = bytes[9], data10 = bytes[10], data11 = bytes[11],
                data12 = bytes[12], data13 = bytes[13], data14 = bytes[14], data15 = bytes[15]
            };
        }

        public static BLEUuid FromString(string uuidStr)
        {
            if (string.IsNullOrEmpty(uuidStr)) return default;
            string clean = uuidStr.Trim().Replace("-", "").Replace("0x", "");
            if (clean.Length == 4)
            {
                return FromGuid(new Guid($"0000{clean}-0000-1000-8000-00805f9b34fb"));
            }
            if (clean.Length == 8)
            {
                return FromGuid(new Guid($"{clean}-0000-1000-8000-00805f9b34fb"));
            }
            return FromGuid(new Guid(uuidStr));
        }

        public Guid ToGuid()
        {
            byte[] bytes = new byte[16] {
                data0, data1, data2, data3, data4, data5, data6, data7,
                data8, data9, data10, data11, data12, data13, data14, data15
            };
            return new Guid(bytes);
        }

        public override string ToString()
        {
            return ToGuid().ToString();
        }
"""
    # Insert helpers right before the closing brace of BLEUuid
    content = re.sub(
        r'(public byte data15;\s*)\}',
        r'\1' + uuid_helpers + '    }',
        content
    )

    return content

def main():
    print("🔄 Generating C# bindings...")

    gen_dir = Path("generate_bindings")
    if not gen_dir.exists():
        print("❌ generate_bindings directory not found")
        return 1

    try:
        result = subprocess.run(
            ["cargo", "run", "--release"],
            cwd=gen_dir,
            capture_output=True,
            text=True,
            check=False
        )

        if result.returncode != 0:
            print("❌ Failed to generate bindings:")
            print(result.stdout)
            print(result.stderr)
            return 1

        print(result.stdout)

        output_file = Path("UnityNativeBLE.generated.cs")
        if not output_file.exists():
            print("❌ Output file not found: UnityNativeBLE.generated.cs")
            return 1

        content = output_file.read_text()
        print("  → Post-processing bindings for Unity marshaling safety...")
        content = post_process_bindings(content)

        runtime_dir = Path("Runtime")
        runtime_dir.mkdir(exist_ok=True)

        final_output = runtime_dir / "UnityNativeBLE.generated.cs"
        final_output.write_text(content)

        if output_file.exists():
            output_file.unlink()

        function_count = content.count("public static extern")
        type_count = content.count("public partial struct")

        print("✅ Done! C# bindings generated to: Runtime/UnityNativeBLE.generated.cs\n")
        print("📊 Summary:")
        print(f"   Total lines: {len(content.splitlines())}")
        print(f"   Functions: {function_count}")
        print(f"   Types: {type_count}")
        print("   Namespace: UnityNativeBLE")
        print("   Native Class: NativeBLE")

        return 0

    except Exception as e:
        print(f"❌ Error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
